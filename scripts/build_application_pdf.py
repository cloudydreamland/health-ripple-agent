def make_table(rows, styles):
    header = rows[0]
    body = rows[1:]
    n_cols = len(header)
    if n_cols == 2:
        ratios = [0.26, 0.74]
    elif n_cols == 3:
        ratios = [0.22, 0.39, 0.39]
    else:
        ratios = [1.0 / n_cols] * n_cols
    col_widths = [r * AVAIL_W for r in ratios]

    data = [[Paragraph("<b>%s</b>" % inline(c), styles["th"]) for c in header]]
    for row in body:
        row = (row + [""] * n_cols)[:n_cols]
        data.append([Paragraph(inline(c), styles["td"]) for c in row])

    table = Table(data, colWidths=col_widths, hAlign="CENTER", repeatRows=1)
    style_cmds = [
        ("BACKGROUND", (0, 0), (-1, 0), HEADER_FILL),
        ("GRID", (0, 0), (-1, -1), 0.4, BORDER),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
    ]
    for i in range(1, len(data)):
        if i % 2 == 0:
            style_cmds.append(("BACKGROUND", (0, i), (-1, i), TABLE_STRIPE))
    table.setStyle(TableStyle(style_cmds))
    return table


def parse_page(block: str):
    """解析单页 markdown → flowable 描述元组列表。"""
    flows = []
    lines = block.splitlines()
    i = 0
    table_buf = []
    while i < len(lines):
        line = lines[i].rstrip()
        is_table = line.startswith("|") and line.endswith("|")
        if is_table:
            cells = [c.strip() for c in line.strip("|").split("|")]
            if not all(re.fullmatch(r":?-{3,}:?", c) for c in cells):
                table_buf.append(cells)
            i += 1
            continue
        if table_buf:
            flows.append(("table", table_buf))
            table_buf = []
        if not line.strip() or line.strip() == "---":
            i += 1
            continue
        if line.startswith("### "):
            flows.append(("h3", line[4:].strip()))
        elif line.startswith("## "):
            flows.append(("h2", line[3:].strip()))
        elif line.startswith("# "):
            flows.append(("h2", line[2:].strip()))
        elif line.startswith("> "):
            flows.append(("body", line[2:].strip()))
        elif line.startswith("- "):
            flows.append(("bullet", line[2:].strip()))
        elif line.startswith("```"):
            code_buf = []
            i += 1
            while i < len(lines) and not lines[i].startswith("```"):
                code_buf.append(lines[i])
                i += 1
            flows.append(("code", "\n".join(code_buf)))
        elif re.match(r"^\d+\. ", line):
            flows.append(("bullet", line))
        else:
            flows.append(("body", line.strip()))
        i += 1
    if table_buf:
        flows.append(("table", table_buf))
    return flows


def page_flows(story, block, styles, images=None):
    count = 0
    for kind, payload in parse_page(block):
        count += 1
        if kind == "h2":
            story.append(CondPageBreak(PAGE_H * 0.12))
            story.append(Paragraph("<b>%s</b>" % inline(payload), styles["h2"]))
        elif kind == "h3":
            story.append(Paragraph("<b>%s</b>" % inline(payload), styles["h3"]))
        elif kind == "body":
            story.append(Paragraph(inline(payload), styles["body"]))
        elif kind == "bullet":
            text = inline(payload)
            if not text.startswith("•"):
                text = "• " + text
            story.append(Paragraph(text, styles["bullet"]))
        elif kind == "code":
            for ln in payload.splitlines() or [""]:
                story.append(Paragraph(inline(ln) if ln.strip() else "&nbsp;", styles["code"]))
        elif kind == "table":
            story.append(Spacer(1, 3))
            story.append(make_table(payload, styles))
            story.append(Spacer(1, 5))
    if images:
        for path, caption in images:
            if not os.path.exists(path):
                continue
            from PIL import Image as PILImage
            with PILImage.open(path) as pil:
                ow, oh = pil.size
            max_w, max_h = AVAIL_W, PAGE_H * 0.34
            ratio = min(max_w / ow, max_h / oh, 1.0)
            story.append(Spacer(1, 4))
            story.append(KeepTogether([
                Image(path, width=ow * ratio, height=oh * ratio),
                Paragraph(caption, styles["caption"]),
            ]))
    return count


def build_body():
    os.makedirs(os.path.dirname(BODY_PDF), exist_ok=True)
    src = io.open(MD_PATH, encoding="utf-8").read()
    parts = PAGE_SEP_RE.split(src)
    pages = {}
    for i in range(1, len(parts), 2):
        pages[int(parts[i])] = parts[i + 1]
    if not pages:
        raise SystemExit("FATAL: 页面分隔标记解析失败，请检查MD文件的编码与分隔符")

    styles = build_styles()
    story = []
    total_flows = 0
    for page_no in range(2, 21):
        block = pages.get(page_no, "")
        images = None
        if page_no == 9 and os.path.exists(IMG_OVERVIEW):
            images = [(IMG_OVERVIEW, "图1：涟漪守护指挥中心——五维涟漪图谱与RII强度总览（真实系统截图，在线推演模式）")]
        if page_no == 15 and os.path.exists(IMG_EVIDENCE):
            images = [(IMG_EVIDENCE, "图2：反事实护栏红锁审计、哈希链证据与五Agent MDT会诊（真实系统截图）")]
        total_flows += page_flows(story, block, styles, images)

    doc = SimpleDocTemplate(
        BODY_PDF, pagesize=A4,
        leftMargin=MARGIN, rightMargin=MARGIN, topMargin=1.5 * cm, bottomMargin=1.6 * cm,
        title="应用方案：健康事件涟漪守护智能体", author="智慧云脑团队", creator="智慧云脑团队",
        subject="2026 iCAN大学生创新创业大赛 AI无代码智能体挑战赛 参赛作品应用方案",
    )
    doc.build(story)
    print("body flowables=%d, md pages parsed=%d" % (total_flows, len(pages)))


