def merge(cover_pdf):
    from pypdf import PdfReader, PdfWriter, Transformation

    A4_W, A4_H = 595.28, 841.89

    def normalize(page):
        box = page.mediabox
        w, h = float(box.width), float(box.height)
        if abs(w - A4_W) > 2 or abs(h - A4_H) > 2:
            page.add_transformation(Transformation().scale(sx=A4_W / w, sy=A4_H / h))
            page.mediabox.lower_left = (0, 0)
            page.mediabox.upper_right = (A4_W, A4_H)
        return page

    writer = PdfWriter()
    writer.add_page(normalize(PdfReader(cover_pdf).pages[0]))
    for page in PdfReader(BODY_PDF).pages:
        writer.add_page(normalize(page))
    writer.add_metadata({
        "/Title": "应用方案：健康事件涟漪守护智能体",
        "/Author": "智慧云脑团队",
        "/Creator": "智慧云脑团队",
        "/Subject": "2026 iCAN大学生创新创业大赛 AI无代码智能体挑战赛 参赛作品应用方案",
    })
    with open(FINAL_PDF, "wb") as f:
        writer.write(f)


